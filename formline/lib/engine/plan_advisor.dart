import 'stock_calibration.dart';
import 'stock_scanner.dart';
import 'stocks.dart';

/// One share the plan says to buy.
class PlanPick {
  PlanPick({required this.code, required this.price, required this.dollars, required this.rank, required this.mom, required this.sellBelow});
  final String code;
  final double price;
  final double dollars; // how much to put on it
  final int rank;
  final double mom; // six-month change
  final double sellBelow; // 200-day average: closing under it is a sell
  int get shares => (dollars / price).floor();
}

/// "Put this much on these shares": the leaders rule sized to an account.
class PlanAdvisor {
  /// How many shares to hold at once for [amount] dollars. The backtest
  /// (tool/plan_backtest.dart) found one share at a time lost money over the
  /// last five years at every account size, so the plan always spreads:
  /// three shares, or five once each parcel is at least $1,000.
  static int slotsFor(double amount) => amount >= 5000 ? 5 : 3;

  /// How many short-term trades to hold at once for [amount] dollars. The
  /// backtest (tool/short_backtest.dart) found one at a time earned the most,
  /// and two at a time from $10,000 fell much less for nearly the same return.
  static int shortSlotsFor(double amount) => amount >= 10000 ? 2 : 1;

  /// What the short-term daily routine did on the last five years of ASX
  /// prices at different starting amounts, paying CMC Invest brokerage:
  /// [amount, yearly return, worst fall, trades a year, brokerage a year].
  /// A yearly return of -1 means brokerage emptied the account.
  /// Generated by tool/short_backtest.dart.
  static const List<List<double>> shortHistory = [
    [300, -1.0000, -1.000, 6, 64],
    [500, -1.0000, -1.000, 10, 105],
    [840, -1.0000, -1.000, 17, 191],
    [1000, -1.0000, -1.000, 19, 228],
    [1500, -1.0000, -1.000, 26, 342],
    [2000, -1.0000, -1.000, 30, 462],
    [3000, -0.4227, -0.953, 47, 776],
    [5000, -0.0130, -0.599, 47, 1030],
    [7500, 0.1200, -0.515, 47, 1042],
    [10000, 0.1261, -0.332, 82, 1797],
    [20000, 0.1997, -0.290, 82, 2676],
    [50000, 0.2008, -0.289, 82, 6676],
  ];

  static List<double> shortHistoryFor(double amount) {
    var best = shortHistory.first;
    for (final row in shortHistory) {
      if (row[0] <= amount) best = row;
    }
    return best;
  }

  /// A true one-day trade (buy the dip at the close, sell at the next close):
  /// share of winners and average gain before brokerage, from the same test.
  static const oneDayTrades = 2046;
  static const oneDayWin = 0.515;
  static const oneDayGross = 0.0014;

  /// What the plan did on the last five years of ASX prices at different
  /// starting amounts, paying CMC Invest brokerage: [amount, yearly return,
  /// worst fall]. Generated by tool/plan_backtest.dart.
  static const List<List<double>> history = [
    [300, -0.1570, -0.576],
    [500, -0.2317, -0.756],
    [840, -0.0355, -0.604],
    [1000, -0.0699, -0.584],
    [1500, 0.0038, -0.551],
    [2000, 0.0337, -0.535],
    [3000, 0.0436, -0.528],
    [5000, 0.0606, -0.446],
    [10000, 0.0748, -0.437],
    [20000, 0.0921, -0.421],
    [50000, 0.1026, -0.411],
  ];

  /// The backtest row nearest to [amount] (never a bigger account's row).
  static List<double> historyFor(double amount) {
    var best = history.first;
    for (final row in history) {
      if (row[0] <= amount) best = row;
    }
    return best;
  }

  /// Whether a share qualifies to be bought: top ten by six-month strength
  /// and above its 200-day average.
  static bool qualifies(String code, DayRanks ranks, Series s) {
    final r = ranks.rank[code];
    if (r == null || r > StockRules.leaderEnter) return false;
    final ma = s.sma(StockRules.trendLen)[s.n - 1];
    return !ma.isNaN && s.close(s.n - 1) > ma;
  }

  /// The best-ranked qualifying shares not already held, [count] of them.
  static List<PlanPick> picks(DayRanks ranks, Map<String, Series> series, {required int count, required double dollarsEach, Set<String> exclude = const {}}) {
    final codes = ranks.rank.keys.where((c) => !exclude.contains(c) && series[c] != null && qualifies(c, ranks, series[c]!)).toList()
      ..sort((a, b) => ranks.rank[a]!.compareTo(ranks.rank[b]!));
    final out = <PlanPick>[];
    for (final c in codes) {
      if (out.length >= count) break;
      final s = series[c]!;
      final price = s.close(s.n - 1);
      // Whole shares only. A share that costs more than the parcel is skipped.
      final shares = (dollarsEach / price).floor();
      if (shares < 1) continue;
      out.add(PlanPick(
        code: c,
        price: price,
        dollars: shares * price,
        rank: ranks.rank[c]!,
        mom: ranks.mom[c] ?? 0,
        sellBelow: s.sma(StockRules.trendLen)[s.n - 1],
      ));
    }
    return out;
  }

  /// Why a held share should be sold now, or null to keep holding.
  static String? sellReason(String code, DayRanks ranks, Series? s) {
    if (s == null) return null;
    final i = s.n - 1;
    final ma = s.sma(StockRules.trendLen)[i];
    if (!ma.isNaN && s.close(i) < ma) return 'it closed below its 200-day average';
    final r = ranks.rank[code];
    if (r == null || r > StockRules.leaderExit) return 'it dropped out of the top ${StockRules.leaderExit}';
    return null;
  }

  /// Average result per trade after brokerage, judged on the last five years.
  static double expectedNet(double roundTripCost) => StockCalibration.leaders.recentGross - roundTripCost;
}
