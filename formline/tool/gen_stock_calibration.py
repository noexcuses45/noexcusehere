"""Turns the share backtest results (tool/backtest_stocks.dart) into
lib/engine/stock_calibration.dart.
Usage: python3 tool/gen_stock_calibration.py <cacheDir>/_results.json lib/engine/stock_calibration.dart
"""
import json
import sys

r = json.load(open(sys.argv[1]))


def stats(d):
    return (f"StrategyStats(trades: {d['n']}, winRate: {d['win']:.4f}, gross: {d['gross']:.5f}, avgWin: {d['avgWin']:.4f}, "
            f"avgLoss: {d['avgLoss']:.4f}, days: {d['days']:.1f}, excess: {d['excess']:.5f}, worst5: {d['worst5']:.4f}, "
            f"best5: {d['best5']:.4f}, recentTrades: {d['n2']}, recentGross: {d['gross2']:.5f}, recentExcess: {d['excess2']:.5f})")


def rejected(key, name):
    d = r[key]
    return f"RejectedIdea('{name}', trades: {d['n']}, winRate: {d['win']:.4f}, net: {d['avg']:.5f}, baseline: {d['base']:.5f})"


out = f'''/// Results of the share-strategy backtest on ten years of ASX daily closes.
/// Generated by tool/gen_stock_calibration.py from tool/backtest_stocks.dart.
class StrategyStats {{
  const StrategyStats({{
    required this.trades,
    required this.winRate,
    required this.gross,
    required this.avgWin,
    required this.avgLoss,
    required this.days,
    required this.excess,
    required this.worst5,
    required this.best5,
    required this.recentTrades,
    required this.recentGross,
    required this.recentExcess,
  }});
  final int trades;
  final double winRate; // share of trades that made money after 0.1% each way
  final double gross; // average return per trade before costs
  final double avgWin, avgLoss; // before costs
  final double days; // average trading days held
  final double excess; // average return above the typical share over the same days
  final double worst5, best5; // 5th and 95th percentile trade
  final int recentTrades; // the most recent five years only
  final double recentGross, recentExcess;

  /// Expected return per trade after paying [costPerSide] on the way in and out.
  double net(double costPerSide) => gross - 2 * costPerSide;
}}

/// A strategy that was tested and left out because it did not beat costs.
class RejectedIdea {{
  const RejectedIdea(this.name, {{required this.trades, required this.winRate, required this.net, required this.baseline}});
  final String name;
  final int trades;
  final double winRate;
  final double net; // average per trade after 0.1% each way
  final double baseline; // just holding any share for the same number of days
}}

class StockCalibration {{
  static const period = '2016 to 2026';
  static const dips = {stats(r['dips'])};
  static const leaders = {stats(r['leaders'])};
  static const rejected = [
    {rejected('pullback_0', 'Buying dips in any uptrending share')},
    {rejected('oversold_0', 'Buying deeply oversold shares')},
    {rejected('band_0', 'Buying shares stretched below their range')},
    {rejected('breakout_0', 'Buying breakouts to new highs')},
  ];
}}
'''
open(sys.argv[2], 'w').write(out)
print('written')
